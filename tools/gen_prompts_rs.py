#!/usr/bin/env python3
"""Generate Rust prompt constants from the Python mem0 prompts module.

Loads `mem0/mem0/configs/prompts.py` standalone (it only depends on the stdlib)
and emits the static string constants as Rust `pub const` raw-string literals.

This mirrors the upstream-port tooling: the prompts are the single most
fidelity-sensitive artifact, so we transcribe them by codegen rather than by
hand. Run from the workspace root:

    python3 mem0-rs/tools/gen_prompts_rs.py
"""
import importlib.util
import os

# Resolve paths relative to the repo root (two levels up from this file).
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
PROMPTS_PY = os.path.join(ROOT, "mem0", "mem0", "configs", "prompts.py")
OUT = os.path.join(
    ROOT, "mem0-rs", "crates", "mem0-core", "src", "prompts", "constants.rs"
)

# Static constants (no runtime f-string interpolation) that the additive
# extraction pipeline and helpers require.
CONSTANTS = [
    "ADDITIVE_EXTRACTION_PROMPT",
    "AGENT_CONTEXT_SUFFIX",
    "PROCEDURAL_MEMORY_SYSTEM_PROMPT",
    "DEFAULT_UPDATE_MEMORY_PROMPT",
    "MEMORY_ANSWER_PROMPT",
]


def load_prompts():
    spec = importlib.util.spec_from_file_location("mem0_prompts_src", PROMPTS_PY)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def rust_raw_string(value: str) -> str:
    """Render a Python string as a Rust raw-string literal with a safe hash fence."""
    n = 1
    while ('"' + "#" * n) in value:
        n += 1
    fence = "#" * n
    return f'r{fence}"{value}"{fence}'


def main():
    module = load_prompts()
    lines = [
        "// @generated by mem0-rs/tools/gen_prompts_rs.py — DO NOT EDIT BY HAND.",
        "// Source: mem0/mem0/configs/prompts.py (mem0ai/mem0 v2.0.4).",
        "// Regenerate with: python3 mem0-rs/tools/gen_prompts_rs.py",
        "",
    ]
    for name in CONSTANTS:
        value = getattr(module, name)
        lines.append(f"pub const {name}: &str = {rust_raw_string(value)};")
        lines.append("")

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as f:
        f.write("\n".join(lines))
    print(f"Wrote {OUT} ({len(CONSTANTS)} constants)")


if __name__ == "__main__":
    main()